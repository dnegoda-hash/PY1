import turtle as t

# 1. Устанавливаем цветовой режим 255, чтобы использовать стандартные значения RGB от 0 до 255
t.colormode(255)

t.ht()          # Скрываем курсор черепашки
t.pensize(5)    # Задаем толщину пера

# 2. Цикл по радиусам: 40, 30, 20, 10
for r in range(40, 0, -10):
    
    # 3. Рисуем 6 кругов для каждого радиуса, поворачивая каждый раз
    for i in range(6):
        # Динамические цвета RGB на основе текущего радиуса 'r'
        t.color(255, 165, r * 6)       # Цвет контура
        t.fillcolor(162, r * 6, 255)   # Цвет заливки
        
        t.begin_fill()
        t.circle(r)                    # Рисуем круг
        t.end_fill()
        
        t.rt(60)                       # Поворот вправо на 60 градусов для следующего круга

# 4. Не закрываем окно, пока не будет выполнен клик
##t.done()
